"""Generate evals/REPORT.md from an eval run (EVALUATION.md, "REPORT.md format").

Nobody edits REPORT.md by hand. The one human input, a one-line cause per failure-gallery tile,
lives in evals/failure_causes.yaml (tile -> cause) and is pulled in on every regeneration.

    python -m evals.report evals/results/full-<time>     (run automatically by --split full)
"""

from __future__ import annotations

import argparse
import csv
import json
from pathlib import Path

import yaml

from depthwizard.config import REPO_ROOT
from evals.visuals import labelled_strip

REPORT = REPO_ROOT / "evals" / "REPORT.md"
CAUSES = REPO_ROOT / "evals" / "failure_causes.yaml"
LANDSCAPES = ["urban", "sparse", "hilly", "forested"]
METHODS = [("dem_only", "DEM only"), ("method_a", "Method A"), ("method_b", "Method B")]
COLUMNS = [
    ("rmse", "RMSE"),
    ("mae", "MAE"),
    ("pearson_r", "r"),
    ("bias", "Bias"),
    ("nmad", "NMAD"),
    ("offset_free_rmse", "Offset-free RMSE"),
    ("ndsm_rmse", "nDSM RMSE"),
]
GALLERY_SIZE = 5
PANEL_PX = 320


def fmt(value, digits: int = 2) -> str:
    return "–" if value in (None, "") else f"{float(value):.{digits}f}"


def build_report(run_dir: Path) -> Path:
    metrics = json.loads((run_dir / "metrics.json").read_text(encoding="utf-8"))
    with (run_dir / "per_tile.csv").open(encoding="utf-8") as f:
        rows = list(csv.DictReader(f))
    causes = yaml.safe_load(CAUSES.read_text(encoding="utf-8")) if CAUSES.exists() else {}
    causes = causes or {}
    summary = metrics["summary"]
    rel = run_dir.relative_to(REPORT.parent).as_posix()

    out = [
        "# DepthWizard evaluation report",
        "",
        "Generated by `python -m evals.run --split full`. Do not edit by hand; failure causes go "
        "in `evals/failure_causes.yaml`.",
        "",
        "## Table 1: accuracy by landscape",
        "",
        "Metres. Each value is the mean of per-tile values over the landscape's test tiles. "
        "Truth: USGS 3DEP LiDAR DSM (NAVD88). Calibration DEM: Copernicus GLO-30 (EGM2008), so raw "
        "RMSE and bias include a datum offset; offset-free RMSE removes it. nDSM RMSE is measured "
        "on buildings and trees only (reference height above ground > "
        f"{metrics.get('object_min_height_m', 2.5)} m).",
        "",
        "| Landscape | Method | Tiles | " + " | ".join(label for _, label in COLUMNS) + " |",
        "|---|---|---|" + "---|" * len(COLUMNS),
    ]
    for landscape in [*LANDSCAPES, "all"]:
        for key, label in METHODS:
            entry = summary.get(landscape, {}).get(key)
            if not entry:
                continue
            digits = {"pearson_r": 3}
            cells = " | ".join(fmt(entry.get(k), digits.get(k, 2)) for k, _ in COLUMNS)
            out.append(f"| {landscape} | {label} | {entry['tiles']} | {cells} |")

    relative = metrics.get("relative_summary")
    if relative:
        out += [
            "",
            "## Table 1b: relative mode (GAMUS, scale-aligned)",
            "",
            "Relative DSMs have no metres. They are fitted to the reference height above ground "
            "with a least-squares scale and shift, then scored. "
            "These numbers are **scale-aligned**.",
            "",
            "| Dataset | Tiles | Scale-aligned RMSE (m) | Scale-aligned MAE (m) | r |",
            "|---|---|---|---|---|",
            f"| GAMUS test | {relative['tiles']} | {fmt(relative['rmse'])} | "
            f"{fmt(relative['mae'])} | {fmt(relative['pearson_r'], 3)} |",
        ]

    scenes = {r["scene"]: r for r in rows if r.get("scene")}  # one timing per site scene
    if scenes:
        sizes = sorted({r["scene_px"] for r in scenes.values()})
        out += [
            "",
            "## Table 2: runtime per pipeline stage",
            "",
            f"Mean over {len(scenes)} site scenes ({', '.join(sizes)} px) on "
            f"{metrics.get('device', 'the eval machine')}; the DEM is read from the local cache.",
            "",
            "| Stage | Seconds per scene |",
            "|---|---|",
        ]
        for key, label in (("scene_depth_s", "depth + stitch"), ("scene_calibrate_s", "calibrate")):
            values = [float(r[key]) for r in scenes.values()]
            out.append(f"| {label} | {sum(values) / len(values):.2f} |")

    method_b = [r for r in rows if r["method"] == "method_b" and r.get("rmse")]
    worst = sorted(method_b, key=lambda r: float(r["rmse"]), reverse=True)[:GALLERY_SIZE]
    if worst:
        out += ["", f"## Failure gallery: the {len(worst)} worst tiles (Method B RMSE)", ""]
        for r in worst:
            stem = r["tile"].replace("/", "_")
            strip = run_dir / "gallery" / f"{stem}.png"
            labelled_strip(
                [
                    ("image", run_dir / "previews" / f"{stem}_image.png"),
                    ("prediction", run_dir / "previews" / f"{stem}_pred.png"),
                    ("reference (LiDAR)", run_dir / "previews" / f"{stem}_ref.png"),
                    ("error", run_dir / "error_maps" / f"{stem}_method_b.png"),
                ],
                PANEL_PX,
                strip,
            )
            cause = (
                causes.get(r["tile"])
                or "_Cause not written yet: add it to evals/failure_causes.yaml._"
            )
            out += [
                f"### {r['tile']} ({r['landscape']})",
                "",
                f"RMSE {fmt(r['rmse'])} m · NMAD {fmt(r['nmad'])} m · "
                f"scale source {r.get('cal_source', '')}",
                "",
                f"![{r['tile']}]({rel}/gallery/{stem}.png)",
                "",
                f"Cause: {cause}",
                "",
            ]

    git = metrics.get("git", {})
    out += [
        "",
        "---",
        f"Run `{metrics['run_id']}` · commit `{git.get('commit', 'unknown')}`"
        f"{' (uncommitted changes)' if git.get('dirty') else ''} · config `{rel}/config.yaml`",
        "",
    ]
    REPORT.write_text("\n".join(out), encoding="utf-8")
    return REPORT


def main() -> None:
    parser = argparse.ArgumentParser(prog="python -m evals.report")
    parser.add_argument("run_dir", type=Path)
    print(build_report(parser.parse_args().run_dir.resolve()))


if __name__ == "__main__":
    main()
